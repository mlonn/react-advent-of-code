#!/usr/bin/env node
// Converts an Advent of Code calendar (the outerHTML of `<pre class="calendar">`, copied from
// the browser's devtools) into a rows file for <ArtCalendar>.
//
// Usage: node scripts/import-calendar.mjs <year> <calendar.html>
// Writes src/pages/<year>/calendarRows.ts and lists the colour keys the palette needs.
import { readFileSync, writeFileSync } from "node:fs";

const [year, file] = process.argv.slice(2);
if (!year || !file) {
  console.error("Usage: node scripts/import-calendar.mjs <year> <calendar.html>");
  process.exit(1);
}

const html = readFileSync(file, "utf8");
const pre = html.match(/<pre class="calendar[^"]*">([\s\S]*?)<\/pre>/);
if (!pre) {
  console.error(`No <pre class="calendar"> found in ${file}`);
  process.exit(1);
}

const decode = (s) =>
  s
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, "&");

const SKIP = Symbol("skip");
const colors = new Set();
const rows = [];

/** Parses calendar HTML into characters tagged with their colour key, dropping day numbers and star marks. */
function parseChars(html) {
  const chars = [];
  const stack = [];
  let skipDepth = 0;
  for (const m of html.matchAll(/<(\/?)(\w+)([^>]*)>|([^<]+)/g)) {
    const [, closing, tag, attrs, text] = m;
    if (text !== undefined) {
      const color = stack.findLast((c) => typeof c === "string");
      if (skipDepth === 0) for (const ch of decode(text)) chars.push({ ch, color });
      continue;
    }
    if (tag !== "span") continue; // <a>, </a>, <i> and anything else only wrap text
    if (closing) {
      if (stack.pop() === SKIP) skipDepth--;
      continue;
    }
    const cls = attrs.match(/class="([^"]*)"/)?.[1] ?? "";
    // The day number and star marks are rendered by <ArtCalendar>, so drop them from the art.
    if (/\bcalendar-(day|mark-[\w-]+)\b/.test(cls)) {
      stack.push(SKIP);
      skipDepth++;
      continue;
    }
    const color = cls
      .split(/\s+/)
      .find((c) => c.startsWith("calendar-color-"))
      ?.slice("calendar-color-".length);
    if (color) colors.add(color);
    stack.push(color ?? null);
  }
  return chars;
}

/** Drops trailing spaces from every line (they're padding before the day number) and groups runs by colour. */
function toSegments(chars) {
  const kept = [];
  for (const c of [...chars, { ch: "\n" }]) {
    if (c.ch === "\n") while (kept.length && kept.at(-1).ch === " ") kept.pop();
    kept.push(c);
  }
  kept.pop();
  const segments = [];
  for (const { ch, color } of kept) {
    const last = segments.at(-1);
    if (last && last.color === color) last.text += ch;
    else segments.push({ text: ch, color });
  }
  return segments;
}

// Each <a> is one day; it may span several lines (2025 uses two). Text between links is static decoration.
for (const piece of pre[1].split(/(<a [^>]*>[\s\S]*?<\/a>)/)) {
  const day = Number(piece.match(/^<a [^>]*class="calendar-day(\d+)\b/)?.[1]) || undefined;
  if (day !== undefined) {
    rows.push({ day, segments: toSegments(parseChars(piece)) });
    continue;
  }
  let line = [];
  for (const c of [...parseChars(piece), { ch: "\n" }]) {
    if (c.ch !== "\n") line.push(c);
    else {
      if (line.length) rows.push({ day: undefined, segments: toSegments(line) });
      line = [];
    }
  }
}

const fmt = ({ text, color }) => (color ? `[${JSON.stringify(text)}, ${JSON.stringify(color)}]` : JSON.stringify(text));
const body = rows.map(({ day, segments }) => `  { ${day ? `day: ${day}, ` : ""}segments: [${segments.map(fmt).join(", ")}] },`).join("\n");

const out = `// Generated by scripts/import-calendar.mjs from the AoC calendar HTML; colours for days whose
// art hasn't been revealed yet may be hand-extrapolated (see the comment on those rows).
import type { CalendarRow } from "../../components/ArtCalendar";

const rows: CalendarRow[] = [
${body}
];

export default rows;
`;

const target = `src/pages/${year}/calendarRows.ts`;
writeFileSync(target, out);
console.log(`Wrote ${target} (${rows.length} rows, ${rows.filter((r) => r.day).length} days)`);
console.log(`Colour keys used: ${[...colors].sort().join(" ")}`);
